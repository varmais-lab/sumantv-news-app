-- SumanTV Shorts — Phase 1 data foundation
-- This migration is intentionally additive because the Supabase project is shared
-- with other SumanTV applications. Every new public object is prefixed with shorts_.

begin;

create schema if not exists shorts_private;

revoke all on schema shorts_private from public, anon;
grant usage on schema shorts_private to authenticated, service_role;

create or replace function shorts_private.is_editor()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce(
    (select auth.jwt()) -> 'app_metadata' ->> 'shorts_role',
    ''
  ) in ('editor', 'admin');
$$;

revoke all on function shorts_private.is_editor() from public, anon;
grant execute on function shorts_private.is_editor() to authenticated, service_role;

create or replace function shorts_private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = pg_catalog.now();
  return new;
end;
$$;

revoke all on function shorts_private.set_updated_at() from public, anon, authenticated;

create table public.shorts_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name_te text not null,
  name_en text not null,
  color text not null default '#f4c94d',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shorts_categories_slug_format
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint shorts_categories_color_format
    check (color ~ '^#[0-9A-Fa-f]{6}$'),
  constraint shorts_categories_names_not_blank
    check (btrim(name_te) <> '' and btrim(name_en) <> '')
);

create table public.shorts_stories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  category_id bigint not null
    references public.shorts_categories(id)
    on update cascade
    on delete restrict,
  title_te text not null,
  title_en text,
  summary_te text not null,
  summary_en text,
  source_name text not null,
  source_url text,
  image_url text,
  image_alt_te text,
  status text not null default 'draft',
  is_breaking boolean not null default false,
  is_live boolean not null default false,
  published_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shorts_stories_slug_format
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint shorts_stories_status
    check (status in ('draft', 'review', 'published', 'archived')),
  constraint shorts_stories_required_text
    check (
      btrim(title_te) <> ''
      and btrim(summary_te) <> ''
      and btrim(source_name) <> ''
    ),
  constraint shorts_stories_source_url_https
    check (source_url is null or source_url ~ '^https://'),
  constraint shorts_stories_image_url_https
    check (image_url is null or image_url ~ '^https://'),
  constraint shorts_stories_publish_timestamp
    check (status <> 'published' or published_at is not null),
  constraint shorts_stories_live_requires_publish
    check (not is_live or status = 'published')
);

create table public.shorts_deals (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title_te text not null,
  description_te text not null,
  current_price numeric(12, 2),
  original_price numeric(12, 2),
  currency text not null default 'INR',
  image_url text,
  destination_url text,
  sponsor_name text,
  sponsorship_disclosure text,
  status text not null default 'draft',
  starts_at timestamptz,
  expires_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shorts_deals_slug_format
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint shorts_deals_status
    check (status in ('draft', 'review', 'published', 'archived')),
  constraint shorts_deals_required_text
    check (btrim(title_te) <> '' and btrim(description_te) <> ''),
  constraint shorts_deals_currency_format
    check (currency ~ '^[A-Z]{3}$'),
  constraint shorts_deals_prices_nonnegative
    check (
      (current_price is null or current_price >= 0)
      and (original_price is null or original_price >= 0)
    ),
  constraint shorts_deals_image_url_https
    check (image_url is null or image_url ~ '^https://'),
  constraint shorts_deals_destination_url_https
    check (destination_url is null or destination_url ~ '^https://'),
  constraint shorts_deals_sponsorship_label
    check (
      sponsor_name is null
      or (
        btrim(sponsor_name) <> ''
        and sponsorship_disclosure is not null
        and btrim(sponsorship_disclosure) <> ''
      )
    ),
  constraint shorts_deals_valid_window
    check (expires_at is null or starts_at is null or expires_at > starts_at),
  constraint shorts_deals_publish_timestamp
    check (status <> 'published' or starts_at is not null)
);

create table public.shorts_leads (
  id bigint generated by default as identity primary key,
  deal_id bigint not null
    references public.shorts_deals(id)
    on update cascade
    on delete restrict,
  full_name text not null,
  phone_e164 text not null,
  city text,
  consent boolean not null,
  consent_text_version text not null,
  source_page text not null default 'shorts-web',
  status text not null default 'new',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shorts_leads_required_name
    check (btrim(full_name) <> ''),
  constraint shorts_leads_phone_e164
    check (phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  constraint shorts_leads_consent_required
    check (consent),
  constraint shorts_leads_status
    check (status in ('new', 'contacted', 'qualified', 'closed', 'deleted'))
);

create table public.shorts_story_reactions (
  user_id uuid not null default auth.uid()
    references auth.users(id)
    on delete cascade,
  story_id bigint not null
    references public.shorts_stories(id)
    on update cascade
    on delete cascade,
  reaction_type text not null default 'like',
  created_at timestamptz not null default now(),
  primary key (user_id, story_id, reaction_type),
  constraint shorts_story_reactions_type
    check (reaction_type in ('like'))
);

create table public.shorts_saved_stories (
  user_id uuid not null default auth.uid()
    references auth.users(id)
    on delete cascade,
  story_id bigint not null
    references public.shorts_stories(id)
    on update cascade
    on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, story_id)
);

create index shorts_stories_public_feed_idx
  on public.shorts_stories (is_breaking desc, published_at desc, id desc)
