create index shorts_stories_updated_by_idx
  on public.shorts_stories (updated_by)
  where updated_by is not null;

create index shorts_deals_public_feed_idx
  on public.shorts_deals (starts_at desc, id desc)
  where status = 'published';

create index shorts_deals_created_by_idx
  on public.shorts_deals (created_by)
  where created_by is not null;

create index shorts_leads_deal_created_idx
  on public.shorts_leads (deal_id, created_at desc);

create index shorts_leads_status_created_idx
  on public.shorts_leads (status, created_at desc);

